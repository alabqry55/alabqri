  function init() {
    if (!document.body) return;
    installControls();
    let preferred = "ar";
    try { preferred = localStorage.getItem("alabqri-language") || "ar"; } catch (_) {}
    setLanguage(preferred);
    const observer = new MutationObserver(records => {
      if (language !== "en") return;
      for (const record of records) {
        if (record.addedNodes) record.addedNodes.forEach(node => {
          if (node.nodeType === 1 || node.nodeType === 3) processTree(node);
        });
        if (record.type === "characterData") translateTextNode(record.target);
      }
    });
    observer.observe(document.body, { childList: true, subtree: true, characterData: true });
    try {
      if (!sessionStorage.getItem("alabqri-welcome-attempted")) {
        sessionStorage.setItem("alabqri-welcome-attempted", "1");
        window.setTimeout(() => speakWelcome(true), 900);
      }
    } catch (_) {}
  }

  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", init, { once: true });
  else init();
