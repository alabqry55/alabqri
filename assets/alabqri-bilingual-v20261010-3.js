  function numberToArabic(n) {
    if (!Number.isFinite(n) || n < 0) return String(n);
    n = Math.floor(n);
    if (n === 0) return "صفر";
    if (n < 1000) return arUnder1000(n);
    if (n < 1000000) {
      const k = Math.floor(n / 1000), r = n % 1000;
      let prefix;
      if (k === 1) prefix = "ألف";
      else if (k === 2) prefix = "ألفان";
      else if (k >= 3 && k <= 10) prefix = arUnder100(k) + " آلاف";
      else prefix = arUnder1000(k) + " ألف";
      return [prefix, r ? arUnder1000(r) : ""].filter(Boolean).join(" و");
    }
    return String(n);
  }

